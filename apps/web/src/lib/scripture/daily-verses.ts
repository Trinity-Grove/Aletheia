export function getDayOfYear(dateStr?: string): number {
  if (dateStr && /^\d{4}-\d{2}-\d{2}$/.test(dateStr)) {
    const [year, month, day] = dateStr.split('-').map(Number);
    if (year && month && day) {
      const targetDate = new Date(Date.UTC(year, month - 1, day));
      const startOfYear = new Date(Date.UTC(year, 0, 1));
      const diffTime = targetDate.getTime() - startOfYear.getTime();
      return Math.max(0, Math.floor(diffTime / (1000 * 60 * 60 * 24)));
    }
  }

  const now = new Date();
  const start = new Date(Date.UTC(now.getFullYear(), 0, 1));
  const today = new Date(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()));
  const diff = today.getTime() - start.getTime();
  return Math.max(0, Math.floor(diff / (1000 * 60 * 60 * 24)));
}

export function getDailyCanonicalVerse(dateOrDateStr?: Date | string): CanonicalVerse {
  const dateStr =
    dateOrDateStr instanceof Date
      ? `${dateOrDateStr.getFullYear()}-${String(dateOrDateStr.getMonth() + 1).padStart(2, '0')}-${String(dateOrDateStr.getDate()).padStart(2, '0')}`
      : dateOrDateStr;

  const dayIndex = getDayOfYear(dateStr);
  const selected = CANONICAL_DAILY_VERSES[dayIndex % CANONICAL_DAILY_VERSES.length];
  return selected || CANONICAL_DAILY_VERSES[0]!;
}
